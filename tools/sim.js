// 渲染管线无头仿真：node tools/sim.js
global.window = global;
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
eval(fs.readFileSync(path.join(root, 'js', 'noise.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'terrain.js'), 'utf8'));
const T = window.GMM.Terrain;
const W = 1600, H = 900;
console.log('makeFields...');
const FF = T.makeFields(W, H);
const img = { data: { buffer: new ArrayBuffer(W * H * 4) } };
console.log('loadDemo...');
T.loadDemo(20260241);
console.log('renderMap...');
const t0 = Date.now();
T.renderMap(FF, img);
console.log('first render', Date.now() - t0, 'ms');
const t1 = Date.now();
for (let r = 0; r < 3; r++) T.renderMap(FF, img);
console.log('steady render', (Date.now() - t1) / 3, 'ms');
const FH = T.makeFields(W / 2, H / 2);
const imgH = { data: { buffer: new ArrayBuffer((W / 2) * (H / 2) * 4) } };
const t2 = Date.now();
for (let r = 0; r < 3; r++) T.renderMap(FH, imgH);
console.log('half preview', (Date.now() - t2) / 3, 'ms');
const u32 = new Uint32Array(img.data.buffer);
let colors = new Set();
for (let i = 0; i < u32.length; i += 997) colors.add(u32[i] & 0xFFFFFF);
console.log('distinct sampled colors:', colors.size);
